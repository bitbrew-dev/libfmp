#!/usr/bin/env python3
"""Audit the generated Go SDK surface against the fmp-py-gen endpoint registry.

Every registry entry must be reachable as a Go method on its namespace struct
(ADR 0030, "Verification gates"). The expected set comes from the registry
TOML under crates/fmp-py-gen/registry/, the actual set from the method
declarations in sdk/go/*.go. The Go names follow the casing rule of the
gen_go emitter (crates/fmp-py-gen/src/bin/gen_go/emit.rs: UpperCamelCase plus
the ADR 0032 initialism table), which this script re-implements so that it
needs neither Rust nor Go tooling.

This is API surface coverage, not execution coverage. A method counts when a
declaration of the form

    func (n *<Domain>Namespace) <Name>(ctx context.Context, ...)

exists; the parity tests and the regeneration gate prove the bodies.

Usage (from the repository root, Python 3.11 or newer for tomllib):

    python3 scripts/check_go_coverage.py            # report only
    python3 scripts/check_go_coverage.py --strict   # exit 1 while anything is missing

Structural errors (a `<domain>.go` without the generated header, or a Go
namespace method the registry does not name) always fail the run. Missing
methods are reported but fail the run only with --strict; the phase 3
tracking issue flips the check_go_sdk.sh invocation to --strict once every
domain is generated.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "crates" / "fmp-py-gen" / "registry"
SDK_GO = ROOT / "sdk" / "go"

GENERATED_HEADER = "// Code generated by fmp-py-gen gen_go. DO NOT EDIT."

METHOD_RE = re.compile(
    r"^func \(\w+ \*(?P<struct>\w+Namespace)\) (?P<name>[A-Z]\w*)\(ctx context\.Context[,)]",
    re.MULTILINE,
)


# The gen_go initialism table (emit.rs `WORDS`, ADR 0032), keyed by the
# lowercase word.
WORDS = {
    "api": "API",
    "ciks": "CIKs",
    "fmp": "FMP",
    "http": "HTTP",
    "ids": "IDs",
    "json": "JSON",
    "url": "URL",
    "urls": "URLs",
    "us": "US",
}


def camel_words(camel: str) -> list[str]:
    """Split CamelCase the way gen_go's `camel_words` does."""
    words: list[str] = []
    start = 0
    for i in range(1, len(camel)):
        prev, cur = camel[i - 1], camel[i]
        nxt = camel[i + 1] if i + 1 < len(camel) else ""
        upper = cur.isupper() and (
            prev.islower() or prev.isdigit() or (prev.isupper() and nxt.islower())
        )
        digit = False
        if cur.isdigit() and prev.isalpha():
            end = i
            while end < len(camel) and camel[end].isdigit():
                end += 1
            digit = end < len(camel) and camel[end].islower()
        if upper or digit:
            words.append(camel[start:i])
            start = i
    if start < len(camel):
        words.append(camel[start:])
    return words


def go_name(camel: str) -> str:
    """Recase a CamelCase name through the initialism table."""
    return "".join(WORDS.get(word.lower(), word) for word in camel_words(camel))


def exported(snake: str) -> str:
    """UpperCamelCase a registry name the way gen_go's `exported` does.

    `batch_quote_short` -> `BatchQuoteShort`, `price_avg_50` -> `PriceAvg50`,
    `etfs` -> `ETFs`, `latest_8k` -> `Latest8K`.
    """
    base = snake.removeprefix("r#")
    return go_name("".join(word[0].upper() + word[1:] for word in base.split("_") if word))


def struct_name(path: list[str]) -> str:
    """`["statements", "income"]` -> `StatementsIncomeNamespace`."""
    return "".join(exported(segment) for segment in path) + "Namespace"


@dataclass(frozen=True, order=True)
class Expected:
    """One registry entry and the Go method it must map to."""

    domain: str
    path: str
    name: str

    @property
    def struct(self) -> str:
        return struct_name(self.path.split("."))

    @property
    def method(self) -> str:
        return exported(self.name)

    @property
    def go_key(self) -> tuple[str, str]:
        return (self.struct, self.method)

    @property
    def registry_key(self) -> str:
        return f"{self.path}.{self.name}"


@dataclass(frozen=True, order=True)
class Actual:
    """One Go namespace method declaration and the file that declares it."""

    struct: str
    method: str
    file: str

    @property
    def go_key(self) -> tuple[str, str]:
        return (self.struct, self.method)


def expected_from_toml(domain: str, text: str) -> list[Expected]:
    """The registry entries of one domain document, root entries first."""
    data = tomllib.loads(text)
    groups = [(domain, data.get("endpoint", []))]
    groups += [(ns["path"], ns.get("endpoint", [])) for ns in data.get("namespace", [])]
    return [Expected(domain, path, e["name"]) for path, endpoints in groups for e in endpoints]


def load_expected(registry: Path = REGISTRY) -> list[Expected]:
    """Every registry entry across every domain file, in file order."""
    return [
        entry
        for toml in sorted(registry.glob("*.toml"))
        for entry in expected_from_toml(toml.stem, toml.read_text())
    ]


def actual_from_source(source: str, file: str) -> list[Actual]:
    """The namespace method declarations in one Go source text."""
    return [Actual(m["struct"], m["name"], file) for m in METHOD_RE.finditer(source)]


def go_sources(sdk_go: Path = SDK_GO) -> list[Path]:
    """The non-test Go files of the module, sorted for a stable report."""
    return sorted(p for p in sdk_go.glob("*.go") if not p.name.endswith("_test.go"))


def load_actual(sdk_go: Path = SDK_GO) -> list[Actual]:
    """Every namespace method declared in the module's non-test Go files."""
    return [
        method
        for path in go_sources(sdk_go)
        for method in actual_from_source(path.read_text(), path.name)
    ]


def has_generated_header(source: str) -> bool:
    return source.partition("\n")[0].rstrip() == GENERATED_HEADER


def generated_domains(domains: list[str], sdk_go: Path = SDK_GO) -> set[str]:
    """The registry domains whose `<domain>.go` carries the generated header.

    Mirrors `generated_domains` in the gen_go binary.
    """
    return {
        domain
        for domain in domains
        if (sdk_go / f"{domain}.go").is_file() and has_generated_header((sdk_go / f"{domain}.go").read_text())
    }


def header_errors(domains: list[str], sdk_go: Path = SDK_GO) -> list[str]:
    """A `<domain>.go` that exists without the generated header is an error."""
    errors = []
    for domain in domains:
        path = sdk_go / f"{domain}.go"
        if path.is_file() and not has_generated_header(path.read_text()):
            errors.append(f"sdk/go/{domain}.go: missing the generated header {GENERATED_HEADER!r}")
    return errors


@dataclass(frozen=True)
class Audit:
    """The outcome of one comparison of the registry with the Go surface."""

    expected: list[Expected]
    actual: list[Actual]
    errors: list[str]

    @property
    def present(self) -> list[Expected]:
        keys = {a.go_key for a in self.actual}
        return [e for e in self.expected if e.go_key in keys]

    @property
    def missing(self) -> list[Expected]:
        keys = {a.go_key for a in self.actual}
        return [e for e in self.expected if e.go_key not in keys]

    @property
    def extra(self) -> list[Actual]:
        keys = {e.go_key for e in self.expected}
        return sorted(a for a in self.actual if a.go_key not in keys)

    def counts_by_domain(self) -> dict[str, tuple[int, int]]:
        """`domain -> (Go methods present, registry methods)` in registry order."""
        keys = {a.go_key for a in self.actual}
        counts: dict[str, tuple[int, int]] = {}
        for entry in self.expected:
            present, total = counts.get(entry.domain, (0, 0))
            counts[entry.domain] = (present + (entry.go_key in keys), total + 1)
        return counts


def audit(registry: Path = REGISTRY, sdk_go: Path = SDK_GO) -> Audit:
    expected = load_expected(registry)
    domains = sorted({e.domain for e in expected})
    return Audit(expected, load_actual(sdk_go), header_errors(domains, sdk_go))


def report(result: Audit) -> str:
    lines = [f"Go methods: {len(result.present)} of {len(result.expected)}"]
    for domain, (present, total) in result.counts_by_domain().items():
        lines.append(f"  {domain}: {present} of {total}")
    missing = result.missing
    if missing:
        lines.append(f"Missing Go methods ({len(missing)}):")
        current = None
        for entry in missing:
            if entry.domain != current:
                current = entry.domain
                lines.append(f"  {current}:")
            lines.append(f"    {entry.registry_key} -> {entry.struct}.{entry.method}")
    for method in result.extra:
        lines.append(f"ERROR: {method.file}: {method.struct}.{method.method} is not a registry method")
    for error in result.errors:
        lines.append(f"ERROR: {error}")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--strict", action="store_true", help="fail when any registry method has no Go method")
    parser.add_argument("--registry", type=Path, default=REGISTRY, help="registry directory (tests only)")
    parser.add_argument("--sdk-go", type=Path, default=SDK_GO, help="Go module directory (tests only)")
    args = parser.parse_args(argv)
    result = audit(args.registry, args.sdk_go)
    print(report(result))
    failed = bool(result.errors or result.extra)
    if args.strict and result.missing:
        print(f"--strict: {len(result.missing)} registry methods have no Go method", file=sys.stderr)
        failed = True
    return int(failed)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
