from __future__ import annotations

import contextlib
import io
import tempfile
import unittest
from pathlib import Path

import check_go_coverage as cov

REGISTRY_TOML = """
[[endpoint]]
name = "full"
method = "quote"

[[endpoint]]
name = "batch_quote_short"
method = "batch_quote_short"

[[namespace]]
path = "statements.income"

[[namespace.endpoint]]
name = "statement"
method = "income_statement"

[[namespace]]
path = "statements.cash_flow"

[[namespace.endpoint]]
name = "statement"
method = "cash_flow_statement"
"""

GO_SOURCE = """\
// Code generated by fmp-py-gen gen_go. DO NOT EDIT.

package fmp

func (q QuoteQuery) Symbol() string {
\treturn q.symbol
}

func (n *QuoteNamespace) Full(ctx context.Context, q QuoteQuery) ([]Quote, error) {
\treturn nil, nil
}

func (n *QuoteNamespace) Etfs(ctx context.Context) ([]QuoteShort, error) {
\treturn nil, nil
}

func (n *StatementsIncomeNamespace) Statement(ctx context.Context, q IncomeStatementQuery) ([]IncomeStatement, error) {
\treturn nil, nil
}

func (n *QuoteNamespace) helper(ctx context.Context) error {
\treturn nil
}
"""


class CasingTest(unittest.TestCase):
    def test_exported_is_mechanical(self) -> None:
        cases = {
            "etfs": "Etfs",
            "batch_quote_short": "BatchQuoteShort",
            "price_avg_50": "PriceAvg50",
            "r#type": "Type",
            "full": "Full",
            "__leading": "Leading",
        }
        for snake, want in cases.items():
            with self.subTest(snake=snake):
                self.assertEqual(cov.exported(snake), want)

    def test_struct_name_concatenates_the_path(self) -> None:
        self.assertEqual(cov.struct_name(["quote"]), "QuoteNamespace")
        self.assertEqual(cov.struct_name(["statements", "income"]), "StatementsIncomeNamespace")
        self.assertEqual(cov.struct_name(["statements", "cash_flow"]), "StatementsCashFlowNamespace")


class RegistryTest(unittest.TestCase):
    def test_expected_covers_root_and_nested_entries(self) -> None:
        entries = cov.expected_from_toml("statements", REGISTRY_TOML)
        self.assertEqual(
            [(e.domain, e.path, e.name) for e in entries],
            [
                ("statements", "statements", "full"),
                ("statements", "statements", "batch_quote_short"),
                ("statements", "statements.income", "statement"),
                ("statements", "statements.cash_flow", "statement"),
            ],
        )
        self.assertEqual(
            [e.go_key for e in entries],
            [
                ("StatementsNamespace", "Full"),
                ("StatementsNamespace", "BatchQuoteShort"),
                ("StatementsIncomeNamespace", "Statement"),
                ("StatementsCashFlowNamespace", "Statement"),
            ],
        )
        self.assertEqual(entries[2].registry_key, "statements.income.statement")


class GoParserTest(unittest.TestCase):
    def test_only_exported_namespace_methods_with_a_context_count(self) -> None:
        methods = cov.actual_from_source(GO_SOURCE, "quote.go")
        self.assertEqual(
            [m.go_key for m in methods],
            [
                ("QuoteNamespace", "Full"),
                ("QuoteNamespace", "Etfs"),
                ("StatementsIncomeNamespace", "Statement"),
            ],
        )
        self.assertTrue(all(m.file == "quote.go" for m in methods))

    def test_header_detection(self) -> None:
        self.assertTrue(cov.has_generated_header(GO_SOURCE))
        self.assertFalse(cov.has_generated_header("package fmp\n"))
        self.assertFalse(cov.has_generated_header("\n" + GO_SOURCE))


class AuditTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        root = Path(self.tmp.name)
        self.registry = root / "registry"
        self.sdk_go = root / "go"
        self.registry.mkdir()
        self.sdk_go.mkdir()
        (self.registry / "quote.toml").write_text(
            '[[endpoint]]\nname = "full"\nmethod = "quote"\n\n[[endpoint]]\nname = "etfs"\nmethod = "etf_quotes"\n'
        )
        (self.registry / "statements.toml").write_text(REGISTRY_TOML)
        (self.sdk_go / "quote.go").write_text(GO_SOURCE)
        (self.sdk_go / "quote_test.go").write_text(
            "package fmp\n\nfunc (n *QuoteNamespace) FromTest(ctx context.Context) error { return nil }\n"
        )

    def test_missing_extra_and_counts(self) -> None:
        result = cov.audit(self.registry, self.sdk_go)
        self.assertEqual(len(result.expected), 6)
        self.assertEqual([e.registry_key for e in result.present], ["quote.full", "quote.etfs", "statements.income.statement"])
        self.assertEqual(
            [e.registry_key for e in result.missing],
            ["statements.full", "statements.batch_quote_short", "statements.cash_flow.statement"],
        )
        self.assertEqual(result.extra, [])
        self.assertEqual(result.errors, [])
        self.assertEqual(result.counts_by_domain(), {"quote": (2, 2), "statements": (1, 4)})
        self.assertEqual(cov.generated_domains(["quote", "statements"], self.sdk_go), {"quote"})

    def test_report_groups_missing_by_domain(self) -> None:
        text = cov.report(cov.audit(self.registry, self.sdk_go))
        self.assertIn("Go methods: 3 of 6\n", text)
        self.assertIn("  quote: 2 of 2\n", text)
        self.assertIn("Missing Go methods (3):\n  statements:\n    statements.full -> StatementsNamespace.Full", text)
        self.assertNotIn("ERROR", text)

    def test_extra_method_and_missing_header_are_errors(self) -> None:
        (self.sdk_go / "client.go").write_text(
            "package fmp\n\nfunc (n *QuoteNamespace) Bogus(ctx context.Context) error { return nil }\n"
        )
        (self.sdk_go / "statements.go").write_text("package fmp\n")
        result = cov.audit(self.registry, self.sdk_go)
        self.assertEqual([(m.file, m.method) for m in result.extra], [("client.go", "Bogus")])
        self.assertEqual(len(result.errors), 1)
        self.assertIn("sdk/go/statements.go: missing the generated header", result.errors[0])
        text = cov.report(result)
        self.assertIn("ERROR: client.go: QuoteNamespace.Bogus is not a registry method", text)

    def test_exit_codes(self) -> None:
        args = ["--registry", str(self.registry), "--sdk-go", str(self.sdk_go)]
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            self.assertEqual(cov.main(args), 0)
            self.assertEqual(cov.main(args + ["--strict"]), 1)
            (self.sdk_go / "statements.go").write_text("package fmp\n")
            self.assertEqual(cov.main(args), 1)


class RealTreeTest(unittest.TestCase):
    """Pins the re-implemented casing to the generated quote.go and the 271-entry registry."""

    def test_registry_has_271_entries(self) -> None:
        self.assertEqual(len(cov.load_expected()), 271)

    def test_generated_quote_domain_matches_expected_names(self) -> None:
        quote_go = cov.SDK_GO / "quote.go"
        self.assertTrue(cov.has_generated_header(quote_go.read_text()))
        actual = {m.go_key for m in cov.actual_from_source(quote_go.read_text(), "quote.go")}
        expected = {e.go_key for e in cov.load_expected() if e.domain == "quote"}
        self.assertEqual(actual, expected)
        self.assertIn(("QuoteNamespace", "Etfs"), actual)
        self.assertIn(("QuoteNamespace", "BatchShort"), actual)


