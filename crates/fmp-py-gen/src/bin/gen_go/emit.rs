//! Text helpers shared by the Go emitters: identifier casing, doc-comment
//! wrapping, the generated-file header, and `gofmt`.

use std::io::Write;
use std::process::{Command, Stdio};

/// The first line of every generated Go file. `golangci-lint` and the
/// no-argument `gen_go` run both recognise it.
pub(crate) const GENERATED_HEADER: &str = "// Code generated by fmp-py-gen gen_go. DO NOT EDIT.";

/// Widest doc-comment line, `// ` included.
const DOC_WIDTH: usize = 79;

/// The Go spelling of every word that is not plainly capitalised (ADR 0032):
/// initialisms in all caps, their plurals with a lowercase `s`, form names,
/// and the TipRanks brand, keyed by the lowercase word. `ipos` follows the
/// ADR (`IposCalendar` -> `IPOCalendar`).
const WORDS: &[(&str, &str)] = &[
    ("api", "API"),
    ("cik", "CIK"),
    ("ciks", "CIKs"),
    ("eps", "EPS"),
    ("etf", "ETF"),
    ("etfs", "ETFs"),
    ("fmp", "FMP"),
    ("http", "HTTP"),
    ("id", "ID"),
    ("ids", "IDs"),
    ("json", "JSON"),
    ("ttm", "TTM"),
    ("url", "URL"),
    ("urls", "URLs"),
    ("us", "US"),
];

/// `batch_quote_short` -> `BatchQuoteShort`, `price_avg_50` -> `PriceAvg50`,
/// `eps_ttm` -> `EPSTTM`, `latest_8k` -> `Latest8K`.
pub(crate) fn exported(snake: &str) -> String {
    let base = snake.strip_prefix("r#").unwrap_or(snake);
    let mut mechanical = String::with_capacity(base.len());
    for word in base.split('_').filter(|word| !word.is_empty()) {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            mechanical.extend(first.to_uppercase());
            mechanical.push_str(chars.as_str());
        }
    }
    go_name(&mechanical)
}

/// Recases a Rust type name word by word through [`WORDS`]:
/// `Form13fFilingDate` -> `Form13FFilingDate`, `KeyMetricsTtm` ->
/// `KeyMetricsTTM`, `Sp500Constituent` -> `SP500Constituent`.
pub(crate) fn go_name(camel: &str) -> String {
    camel_words(camel)
        .into_iter()
        .map(|word| spelled(word).unwrap_or(word))
        .collect()
}

fn spelled(word: &str) -> Option<&'static str> {
    let lower = word.to_ascii_lowercase();
    WORDS
        .iter()
        .find(|(key, _)| *key == lower)
        .map(|(_, go)| *go)
}

/// Splits a CamelCase name into words. A word starts at an uppercase letter
/// after a lowercase letter or a digit, at the last capital of an uppercase
/// run followed by a lowercase letter, and at a digit run that follows a
/// letter and ends in a lowercase letter (`Form13f` -> `Form`, `13f`).
fn camel_words(camel: &str) -> Vec<&str> {
    let bytes = camel.as_bytes();
    let mut words = Vec::new();
    let mut start = 0;
    for i in 1..bytes.len() {
        let (prev, cur) = (bytes[i - 1], bytes[i]);
        let next = bytes.get(i + 1).copied();
        let upper_boundary = cur.is_ascii_uppercase()
            && (prev.is_ascii_lowercase()
                || prev.is_ascii_digit()
                || (prev.is_ascii_uppercase() && next.is_some_and(|c| c.is_ascii_lowercase())));
        let digit_boundary = cur.is_ascii_digit() && prev.is_ascii_alphabetic() && {
            let end = bytes[i..]
                .iter()
                .position(|c| !c.is_ascii_digit())
                .map_or(bytes.len(), |n| i + n);
            bytes.get(end).is_some_and(u8::is_ascii_lowercase)
        };
        if upper_boundary || digit_boundary {
            words.push(&camel[start..i]);
            start = i;
        }
    }
    if start < camel.len() {
        words.push(&camel[start..]);
    }
    words
}

/// `QuoteShort` -> `quoteShort`, `CIKListing` -> `cikListing`, `ETFsQuery`
/// -> `etfsQuery`: a leading all-caps word of [`WORDS`] is lowercased whole,
/// as Go spells an unexported initialism.
pub(crate) fn lower_first(name: &str) -> String {
    let lead = WORDS
        .iter()
        .map(|(_, go)| *go)
        .filter(|go| {
            go.as_bytes()
                .get(1)
                .is_some_and(|c| !c.is_ascii_lowercase())
        })
        .filter(|go| {
            name.strip_prefix(*go)
                .is_some_and(|rest| !rest.starts_with(|c: char| c.is_ascii_lowercase()))
        })
        .max_by_key(|go| go.len());
    if let Some(lead) = lead {
        return lead.to_ascii_lowercase() + &name[lead.len()..];
    }
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_lowercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

/// A lowerCamelCase Go identifier for a registry arg name, with a trailing
/// underscore when the result is a Go keyword (`type` -> `type_`).
pub(crate) fn local_ident(snake: &str) -> String {
    let ident = lower_first(&exported(snake));
    if is_go_keyword(&ident) {
        format!("{ident}_")
    } else {
        ident
    }
}

fn is_go_keyword(name: &str) -> bool {
    const KEYWORDS: &[&str] = &[
        "break",
        "case",
        "chan",
        "const",
        "continue",
        "default",
        "defer",
        "else",
        "fallthrough",
        "for",
        "func",
        "go",
        "goto",
        "if",
        "import",
        "interface",
        "map",
        "package",
        "range",
        "return",
        "select",
        "struct",
        "switch",
        "type",
        "var",
    ];
    KEYWORDS.contains(&name)
}

/// Lowercases the first character of a sentence unless the second is also
/// uppercase, so "US aftermarket" keeps its initialism.
pub(crate) fn lower_lead(text: &str) -> String {
    let mut chars = text.chars();
    let Some(first) = chars.next() else {
        return String::new();
    };
    let rest = chars.as_str();
    let second_upper = rest.chars().next().is_some_and(char::is_uppercase);
    if second_upper {
        text.to_string()
    } else {
        first.to_lowercase().collect::<String>() + rest
    }
}

/// Renders one paragraph as `// ` lines greedily wrapped at [`DOC_WIDTH`].
pub(crate) fn doc_comment(text: &str) -> String {
    let mut out = String::new();
    let mut line = String::from("//");
    for word in text.split_whitespace() {
        if line.len() > 2 && line.len() + 1 + word.len() > DOC_WIDTH {
            out.push_str(&line);
            out.push('\n');
            line = String::from("//");
        }
        line.push(' ');
        line.push_str(word);
    }
    if line.len() > 2 {
        out.push_str(&line);
        out.push('\n');
    }
    out
}

/// Formats Go source through `gofmt` on stdin, so a file is only ever
/// written already formatted. A missing `gofmt` is an error, like a missing
/// `rustfmt` for `gen_models`.
pub(crate) fn gofmt(source: &str) -> Result<String, String> {
    let mut child = Command::new("gofmt")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|error| format!("cannot run gofmt (is Go installed?): {error}"))?;
    child
        .stdin
        .take()
        .ok_or("gofmt stdin is unavailable")?
        .write_all(source.as_bytes())
        .map_err(|error| format!("cannot write to gofmt: {error}"))?;
    let output = child
        .wait_with_output()
        .map_err(|error| format!("gofmt did not finish: {error}"))?;
    if !output.status.success() {
        return Err(format!(
            "gofmt rejected the generated source:\n{}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    String::from_utf8(output.stdout).map_err(|error| format!("gofmt output is not UTF-8: {error}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn casing_follows_the_initialism_table() {
        assert_eq!(exported("batch_quote_short"), "BatchQuoteShort");
        assert_eq!(exported("price_avg_50"), "PriceAvg50");
        assert_eq!(exported("r#type"), "Type");
        assert_eq!(go_name("UsDate"), "USDate");
        assert_eq!(lower_first("QuoteShort"), "quoteShort");
        assert_eq!(lower_first("USDate"), "usDate");
        assert_eq!(lower_first("Usage"), "usage");
        assert_eq!(local_ident("symbol"), "symbol");
        assert_eq!(local_ident("from_date"), "fromDate");
        assert_eq!(local_ident("type"), "type_");
        assert_eq!(local_ident("range"), "range_");
    }

    #[test]
    fn lower_lead_keeps_initialisms() {
        assert_eq!(lower_lead("A detailed quote."), "a detailed quote.");
        assert_eq!(
            lower_lead("US aftermarket trades."),
            "US aftermarket trades."
        );
        assert_eq!(lower_lead(""), "");
    }

    #[test]
    fn doc_comment_wraps_at_the_width() {
        let text = "QuoteShort is the compact response returned by quote-short endpoints across asset classes.";
        assert_eq!(
            doc_comment(text),
            "// QuoteShort is the compact response returned by quote-short endpoints across\n// asset classes.\n"
        );
        assert_eq!(doc_comment("  short  "), "// short\n");
        assert_eq!(doc_comment(""), "");
    }
}
