//! Committed-source generator for the `fmp-py` endpoint namespaces.
//!
//! Reads the endpoint registry under `crates/fmp-py-gen/registry`, validates
//! it against the real `libfmp` signatures (refusing to emit on any error),
//! and writes one frozen `pyclass` namespace per registry path under
//! `crates/fmp-py/src/namespaces/`: flat domains as `<domain>.rs`, nested
//! ones as `<domain>/mod.rs` plus `<domain>/<sub>.rs`, each formatted with
//! `rustfmt`. Run it with `cargo run -p fmp-py-gen --bin gen_namespaces`.
//! The top-level `namespaces/mod.rs` stays hand-written.

mod emit;
mod method;
mod plan;

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use fmp_py_gen::registry::{Registry, RegistryError, Report, format_errors};

use crate::emit::{QueryModules, Rendered, render};
use crate::plan::{Node, build_tree};

pub(crate) const GENERATED_HEADER: &str = "// @generated by gen_namespaces; do not edit by hand.";
const RUST_EDITION: &str = "2024";

type BoxError = Box<dyn std::error::Error>;

fn main() -> ExitCode {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let registry_dir = std::env::args()
        .nth(1)
        .map_or_else(|| manifest.join("registry"), PathBuf::from);
    let endpoints_root = manifest.join("../libfmp/src/endpoints");
    let models_root = manifest.join("../fmp-py/src/models");
    let namespaces_root = manifest.join("../fmp-py/src/namespaces");

    let registry = match Registry::load(&registry_dir) {
        Ok(registry) => registry,
        Err(RegistryError::Invalid(errors)) => {
            eprintln!("{}", format_errors(&errors));
            eprintln!(
                "registry invalid: {} error(s); nothing emitted",
                errors.len()
            );
            return ExitCode::FAILURE;
        }
        Err(error) => {
            eprintln!("{error}");
            return ExitCode::FAILURE;
        }
    };
    let report = match registry.validate(&endpoints_root, &models_root) {
        Ok(report) => report,
        Err(errors) => {
            eprintln!("{}", format_errors(&errors));
            eprintln!(
                "registry invalid: {} error(s); nothing emitted",
                errors.len()
            );
            return ExitCode::FAILURE;
        }
    };

    match generate(&registry, &report, &namespaces_root) {
        Ok(written) => {
            for file in &written {
                println!("wrote {}", file.display());
            }
            println!("emitted {} namespace file(s)", written.len());
            ExitCode::SUCCESS
        }
        Err(error) => {
            eprintln!("{error}");
            ExitCode::FAILURE
        }
    }
}

/// Renders every node of the tree, writes the files, and formats them.
fn generate(registry: &Registry, report: &Report, root: &Path) -> Result<Vec<PathBuf>, BoxError> {
    let query_modules = query_modules(report);
    let mut written = Vec::new();
    for node in build_tree(registry).values() {
        let file = node.file(root);
        let rendered = render_node(node, &query_modules)?;
        for entry in &rendered.skipped {
            println!("skipped {entry}: binary entries are not emitted by the sync arm");
        }
        if let Some(parent) = file.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&file, rendered.source)?;
        written.push(file);
    }
    run_rustfmt(&written)?;
    Ok(written)
}

/// The query module of every verified entry, keyed by dotted entry.
pub(crate) fn query_modules(report: &Report) -> QueryModules {
    let mut modules = BTreeMap::new();
    for entry in &report.verified {
        if let Some(module) = &entry.query_module {
            modules.insert(entry.entry.clone(), module.clone());
        }
    }
    modules
}

fn render_node(node: &Node, query_modules: &QueryModules) -> Result<Rendered, BoxError> {
    Ok(render(node, query_modules)?)
}

/// Formats every generated file with `rustfmt`.
fn run_rustfmt(files: &[PathBuf]) -> Result<(), BoxError> {
    if files.is_empty() {
        return Ok(());
    }
    let mut command = Command::new("rustfmt");
    command.arg("--edition").arg(RUST_EDITION);
    for file in files {
        command.arg(file);
    }
    let status = command.status()?;
    if !status.success() {
        return Err(format!("rustfmt failed with status {status}").into());
    }
    Ok(())
}
