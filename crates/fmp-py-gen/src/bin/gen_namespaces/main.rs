use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use fmp_py_gen::registry::{Registry, RegistryError, Report, format_errors};

use crate::bindings::{
    build_bindings, render_client_namespaces, render_facade_domains, render_namespaces_mod,
    render_registration,
};
use crate::emit::{EntryModules, QueryModules, Rendered, render};
use crate::models::scan_models;
use crate::plan::{Node, build_tree};

pub(crate) const GENERATED_HEADER: &str = "// @generated by gen_namespaces; do not edit by hand.";
const RUST_EDITION: &str = "2024";

type BoxError = Box<dyn std::error::Error>;

fn main() -> ExitCode {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let registry_dir = std::env::args()
        .nth(1)
        .map_or_else(|| manifest.join("registry"), PathBuf::from);
    let endpoints_root = manifest.join("../libfmp/src/endpoints");
    let src_root = manifest.join("../fmp-py/src");
    let models_root = src_root.join("models");
    let namespaces_root = src_root.join("namespaces");

    let registry = match Registry::load(&registry_dir) {
        Ok(registry) => registry,
        Err(RegistryError::Invalid(errors)) => {
            eprintln!("{}", format_errors(&errors));
            eprintln!(
                "registry invalid: {} error(s); nothing emitted",
                errors.len()
            );
            return ExitCode::FAILURE;
        }
        Err(error) => {
            eprintln!("{error}");
            return ExitCode::FAILURE;
        }
    };
    let report = match registry.validate(&endpoints_root, &models_root) {
        Ok(report) => report,
        Err(errors) => {
            eprintln!("{}", format_errors(&errors));
            eprintln!(
                "registry invalid: {} error(s); nothing emitted",
                errors.len()
            );
            return ExitCode::FAILURE;
        }
    };

    match generate(
        &registry,
        &report,
        &models_root,
        &namespaces_root,
        &src_root,
    ) {
        Ok(written) => {
            for file in &written {
                println!("wrote {}", file.display());
            }
            println!("emitted {} file(s)", written.len());
            ExitCode::SUCCESS
        }
        Err(error) => {
            eprintln!("{error}");
            ExitCode::FAILURE
        }
    }
}

/// Renders every node of the tree plus the binding files, writes them, and
/// formats them.
fn generate(
    registry: &Registry,
    report: &Report,
    models_root: &Path,
    namespaces_root: &Path,
    src_root: &Path,
) -> Result<Vec<PathBuf>, BoxError> {
    let query_modules = query_modules(report);
    let tree = build_tree(registry);
    let mut written = Vec::new();
    for node in tree.values() {
        let file = node.file(namespaces_root);
        let rendered = render_node(node, &query_modules)?;
        write_file(&file, &rendered.source, &mut written)?;
    }

    let bindings = build_bindings(&scan_models(models_root)?, &tree);
    write_file(
        &namespaces_root.join("mod.rs"),
        &render_namespaces_mod(&tree),
        &mut written,
    )?;
    write_file(
        &src_root.join("registration.rs"),
        &render_registration(&bindings),
        &mut written,
    )?;
    write_file(
        &src_root.join("client_namespaces.rs"),
        &render_client_namespaces(&tree),
        &mut written,
    )?;
    write_file(
        &src_root.join("facade_domains.rs"),
        &render_facade_domains(&bindings),
        &mut written,
    )?;
    run_rustfmt(&written)?;
    Ok(written)
}

fn write_file(file: &Path, source: &str, written: &mut Vec<PathBuf>) -> Result<(), BoxError> {
    if let Some(parent) = file.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(file, source)?;
    written.push(file.to_path_buf());
    Ok(())
}

/// The query and nested builder modules of every verified entry, keyed by
/// dotted entry.
pub(crate) fn query_modules(report: &Report) -> QueryModules {
    let mut modules = BTreeMap::new();
    for entry in &report.verified {
        if let Some(module) = &entry.query_module {
            modules.insert(
                entry.entry.clone(),
                EntryModules {
                    query: module.clone(),
                    nested: entry.nested_modules.clone(),
                },
            );
        }
    }
    modules
}

fn render_node(node: &Node, query_modules: &QueryModules) -> Result<Rendered, BoxError> {
    Ok(render(node, query_modules)?)
}

/// Formats every generated file with `rustfmt`.
fn run_rustfmt(files: &[PathBuf]) -> Result<(), BoxError> {
    if files.is_empty() {
        return Ok(());
    }
    let mut command = Command::new("rustfmt");
    command.arg("--edition").arg(RUST_EDITION);
    for file in files {
        command.arg(file);
    }
    let status = command.status()?;
    if !status.success() {
        return Err(format!("rustfmt failed with status {status}").into());
    }
    Ok(())
}
