//! Emitter contract: the shipped quote registry renders the drop-in
//! `QuoteNamespace`, nested fixtures render parents with getters and binary
//! entries as `BinaryPayload` methods, keyword arg names are sanitized, and
//! every rendered file parses as Rust.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use fmp_py_gen::registry::{Arg, ArgKind, Endpoint, ModelPath, Registry};

use crate::bindings::{
    Binding, build_bindings, render_client_namespaces, render_facade_domains,
    render_namespaces_mod, render_registration,
};
use crate::emit::{EmitError, QueryModules, Rendered, render};
use crate::models::scan_models;
use crate::plan::{Node, build_tree, struct_name_for};
use crate::query_modules;

fn manifest() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn load(dir: &Path) -> (Registry, QueryModules) {
    let registry = Registry::load(dir).expect("registry loads");
    let report = registry
        .validate(
            &manifest().join("../libfmp/src/endpoints"),
            &manifest().join("../fmp-py/src/models"),
        )
        .expect("registry validates");
    (registry, query_modules(&report))
}

fn render_all(dir: &Path) -> BTreeMap<PathBuf, Rendered> {
    let (registry, modules) = load(dir);
    build_tree(&registry)
        .values()
        .map(|node| {
            let rendered = render(node, &modules).expect("node renders");
            syn::parse_file(&rendered.source).unwrap_or_else(|error| {
                panic!(
                    "{} does not parse: {error}\n{}",
                    node.dotted(),
                    rendered.source
                )
            });
            (node.file(Path::new("")), rendered)
        })
        .collect()
}

fn source<'a>(files: &'a BTreeMap<PathBuf, Rendered>, file: &str) -> &'a str {
    &files
        .get(Path::new(file))
        .unwrap_or_else(|| panic!("{file} was not rendered; got {:?}", files.keys()))
        .source
}

#[test]
fn quote_registry_renders_the_drop_in_namespace() {
    let files = render_all(&manifest().join("registry"));
    let quote = source(&files, "quote.rs");
    assert!(quote.starts_with("// @generated by gen_namespaces; do not edit by hand.\n"));
    for needle in [
        "#[pyclass(module = \"fmp._native.quote\", frozen)]",
        "pub(crate) struct QuoteNamespace {",
        "pub(crate) fn new(builder: Arc<ClientBuilder>) -> Self",
        "use libfmp::endpoints::quote::{",
        "QuoteQuery, QuoteShortQuery",
        "use crate::models::quote::{",
        "Quote, QuoteShort",
        "/// Quote endpoints for a single client, exposed as `client.quote`.",
        "    /// The full quote for a symbol.\n    #[pyo3(signature = (symbol))]\n    fn full(&self, py: Python<'_>, symbol: &str) -> PyResult<Vec<Quote>> {",
        "let query = full_query(symbol)?;",
        "client.quote(query).await",
        "fn mutual_funds(&self, py: Python<'_>) -> PyResult<Vec<QuoteShort>> {",
        "client.mutual_fund_quotes().await",
        "fn short_query(symbol: &str) -> PyResult<QuoteShortQuery> {\n    let symbol = args::ticker(\"symbol\", symbol)?;\n    Ok(QuoteShortQuery::new(symbol))\n}",
    ] {
        assert!(quote.contains(needle), "missing {needle:?} in:\n{quote}");
    }
    assert!(!quote.contains("#[getter]"));
    assert!(!quote.contains("BinaryPayload"));
}

#[test]
fn nested_fixture_renders_parent_getters_and_children() {
    let files = render_all(&manifest().join("tests/fixtures/nested"));
    let keys: Vec<&Path> = files.keys().map(PathBuf::as_path).collect();
    assert_eq!(
        keys,
        [
            Path::new("statements/income.rs"),
            Path::new("statements/mod.rs"),
            Path::new("statements/reports.rs"),
        ]
    );

    let parent = source(&files, "statements/mod.rs");
    for needle in [
        "pub(crate) mod income;\npub(crate) mod reports;",
        "use self::income::StatementsIncomeNamespace;",
        "#[pyclass(module = \"fmp._native.statements\", frozen)]",
        "pub(crate) struct StatementsNamespace {",
        "    #[getter]\n    fn income(&self) -> StatementsIncomeNamespace {\n        StatementsIncomeNamespace::new(self.builder.clone())\n    }",
        "    #[getter]\n    fn reports(&self) -> StatementsReportsNamespace {",
    ] {
        assert!(parent.contains(needle), "missing {needle:?} in:\n{parent}");
    }
    assert!(!parent.contains("use crate::args;"));
    assert!(!parent.contains("block_on"));

    let income = source(&files, "statements/income.rs");
    for needle in [
        "use libfmp::endpoints::statements::IncomeStatementQuery;",
        "use crate::models::statements::income::IncomeStatement;",
        "#[pyclass(module = \"fmp._native.statements.income\", frozen)]",
        "pub(crate) struct StatementsIncomeNamespace {",
        "#[pyo3(signature = (symbol, *, limit=None, period=None))]",
        "fn statement(&self, py: Python<'_>, symbol: &str, limit: Option<i64>, period: Option<&str>) -> PyResult<Vec<IncomeStatement>> {",
        "let query = statement_query(symbol, limit, period)?;",
        "let limit = args::optional(\"limit\", limit, args::limit)?;",
        "let period = args::optional(\"period\", period, args::statement_period)?;",
        "let mut query = IncomeStatementQuery::new(symbol);",
        "if let Some(limit) = limit {\n        query = query.with_limit(limit);\n    }",
        "query = query.with_period(period);",
    ] {
        assert!(income.contains(needle), "missing {needle:?} in:\n{income}");
    }

    let reports = source(&files, "statements/reports.rs");
    for needle in [
        "use libfmp::endpoints::statements::reports::FinancialReportsXlsxQuery;",
        "use crate::args;\nuse crate::binary::BinaryPayload;\nuse crate::errors::to_py_error;\nuse crate::runtime::block_on;\n",
        "pub(crate) struct StatementsReportsNamespace {",
        "    /// Downloads one financial report as an XLSX workbook.\n    #[pyo3(signature = (symbol, year, period))]\n    fn financial_reports_xlsx(&self, py: Python<'_>, symbol: &str, year: i64, period: &str) -> PyResult<BinaryPayload> {",
        "let query = financial_reports_xlsx_query(symbol, year, period)?;",
        "let response = py.detach(move || block_on(builder, |client| async move { client.financial_reports_xlsx(query).await }))?;",
        "        response.map(BinaryPayload::from).map_err(to_py_error)\n    }",
        "fn financial_reports_xlsx_query(symbol: &str, year: i64, period: &str) -> PyResult<FinancialReportsXlsxQuery> {",
        "let period = args::fiscal_period(\"period\", period)?;",
        "Ok(FinancialReportsXlsxQuery::new(symbol, year, period))",
    ] {
        assert!(
            reports.contains(needle),
            "missing {needle:?} in:\n{reports}"
        );
    }
    assert!(!reports.contains("Vec<"));
    assert!(!reports.contains("use crate::models"));
    assert!(!reports.contains("rows"));
}

