#[test]
fn unresolved_query_type_is_an_error() {
    let (registry, _) = load(&manifest().join("registry"));
    let tree = build_tree(&registry);
    let node = &tree[&vec!["quote".to_owned()]];
    let error = render(node, &QueryModules::new()).expect_err("no module for QuoteQuery");
    assert!(matches!(
        error,
        EmitError::UnresolvedQuery { ref entry, ref query } if entry == "quote.full" && query == "QuoteQuery"
    ));
    assert!(
        error
            .to_string()
            .contains("`quote.full`: query type `QuoteQuery`")
    );
}

fn synthetic(args: Vec<Arg>) -> Node {
    Node {
        path: vec!["calendar".to_owned()],
        endpoints: vec![Endpoint {
            python_name: "wide".to_owned(),
            libfmp_method: "wide_call".to_owned(),
            query_type: Some("WideQuery".to_owned()),
            response_model: Some(ModelPath {
                module: vec!["calendar".to_owned()],
                name: "Row".to_owned(),
            }),
            doc: "A wide method.\n\nSecond paragraph.".to_owned(),
            args,
            setters: Vec::new(),
            binary: false,
        }],
        children: Default::default(),
    }
}

fn arg(name: &str, kind: ArgKind, required: bool) -> Arg {
    Arg {
        name: name.to_owned(),
        kind,
        required,
    }
}

#[test]
fn wide_signatures_get_the_clippy_allow_and_prefixed_input_types() {
    let modules: QueryModules = [("calendar.wide".to_owned(), vec!["calendar".to_owned()])]
        .into_iter()
        .collect();
    let six = synthetic(vec![
        arg("symbols", ArgKind::TickerList, true),
        arg("range", ArgKind::DateRange, true),
        arg("page", ArgKind::Page, false),
        arg("since", ArgKind::ApiDatetime, false),
        arg("active", ArgKind::TrueFalseFlag, false),
        arg("party", ArgKind::Text, false),
    ]);
    let rendered = render(&six, &modules).expect("renders");
    syn::parse_file(&rendered.source).expect("parses");
    let source = rendered.source;
    for needle in [
        "    /// A wide method.\n    ///\n    /// Second paragraph.\n",
        "#[pyo3(signature = (symbols, range, *, page=None, since=None, active=None, party=None))]\n    #[allow(clippy::too_many_arguments)]\n    fn wide(",
        "symbols: args::SymbolsArg, range: (args::DateArg, args::DateArg), page: Option<i64>, since: Option<args::DateTimeArg>, active: Option<bool>, party: Option<&str>",
        "let party = args::optional(\"party\", party, args::text)?;",
        "Ok(WideQuery::new(symbols, range, page, since, active, party))",
    ] {
        assert!(source.contains(needle), "missing {needle:?} in:\n{source}");
    }
    assert!(!source.contains("#[allow(clippy::too_many_arguments)]\nfn wide_query"));

    let eight = synthetic(
        (0..8)
            .map(|index| arg(&format!("field{index}"), ArgKind::Cik, true))
            .collect(),
    );
    let source = render(&eight, &modules).expect("renders").source;
    assert!(source.contains("#[allow(clippy::too_many_arguments)]\nfn wide_query("));
}

#[test]
fn struct_names_join_the_full_path() {
    let path =
        |segments: &[&str]| -> Vec<String> { segments.iter().map(|s| (*s).to_owned()).collect() };
    assert_eq!(struct_name_for(&path(&["quote"])), "QuoteNamespace");
    assert_eq!(
        struct_name_for(&path(&["statements", "as_reported"])),
        "StatementsAsReportedNamespace"
    );
    let leaf = Node {
        path: path(&["market_hours"]),
        ..Node::default()
    };
    assert_eq!(leaf.file(Path::new("ns")), Path::new("ns/market_hours.rs"));
}

fn bindings_for(dir: &Path) -> BTreeMap<Vec<String>, Binding> {
    let (registry, _) = load(dir);
    let models = scan_models(&manifest().join("../fmp-py/src/models")).expect("models scan");
    build_bindings(&models, &build_tree(&registry))
}

fn path(dotted: &str) -> Vec<String> {
    dotted.split('.').map(str::to_owned).collect()
}

#[test]
fn model_scan_reads_every_pyclass_module_back() {
    let models = scan_models(&manifest().join("../fmp-py/src/models")).expect("models scan");
    assert!(models[&path("quote")].contains(&"QuoteShort".to_owned()));
    assert!(
        models[&path("statements.growth.income")].contains(&"IncomeStatementGrowth".to_owned())
    );
    assert!(!models.contains_key(&path("convert")));
    assert!(!models.contains_key(&path("statements")));
}

#[test]
fn bindings_union_models_with_the_registry_tree() {
    let bindings = bindings_for(&manifest().join("registry"));
    let quote = &bindings[&path("quote")];
    assert_eq!(quote.namespace.as_deref(), Some("QuoteNamespace"));
    assert!(quote.models.contains(&"Quote".to_owned()));
    let statements = &bindings[&path("statements")];
    assert!(statements.models.is_empty());
    assert!(statements.children.contains("growth"));
    assert!(
        bindings[&path("statements.growth")]
            .children
            .contains("income")
    );

    let nested = bindings_for(&manifest().join("tests/fixtures/nested"));
    assert_eq!(
        nested[&path("statements.income")].namespace.as_deref(),
        Some("StatementsIncomeNamespace")
    );
    assert_eq!(
        nested[&path("statements")].namespace.as_deref(),
        Some("StatementsNamespace")
    );
}

#[test]
fn binding_files_render_the_wiring_and_parse() {
    let (registry, _) = load(&manifest().join("tests/fixtures/nested"));
    let tree = build_tree(&registry);
    let bindings = bindings_for(&manifest().join("tests/fixtures/nested"));

    let registration = render_registration(&bindings);
    syn::parse_file(&registration).expect("registration parses");
    for needle in [
        "pub(crate) fn register_namespaces(parent: &Bound<'_, PyModule>) -> PyResult<()> {\n    register_analyst(parent)?;",
        "fn register_statements(parent: &Bound<'_, PyModule>) -> PyResult<()> {\n    let module = PyModule::new(parent.py(), \"statements\")?;\n    module.add_class::<crate::namespaces::statements::StatementsNamespace>()?;\n    register_statements_as_reported(&module)?;",
        "    module.add_class::<crate::models::statements::income::IncomeStatement>()?;\n    module.add_class::<crate::namespaces::statements::income::StatementsIncomeNamespace>()?;\n    add_submodule(parent, \"fmp._native.statements.income\", &module)\n}",
    ] {
        assert!(
            registration.contains(needle),
            "missing {needle:?} in:\n{registration}"
        );
    }

    let getters = render_client_namespaces(&tree);
    syn::parse_file(&getters).expect("client getters parse");
    assert!(getters.contains("use crate::namespaces::statements::StatementsNamespace;"));
    assert!(getters.contains("    #[getter]\n    fn statements(&self) -> StatementsNamespace {"));
    assert!(!getters.contains("fn income("));

    let namespaces_mod = render_namespaces_mod(&tree);
    syn::parse_file(&namespaces_mod).expect("namespaces mod parses");
    assert_eq!(
        namespaces_mod,
        "// @generated by gen_namespaces; do not edit by hand.\n\npub(crate) mod statements;\n"
    );

    let facade = render_facade_domains(&bindings);
    syn::parse_file(&facade).expect("facade domains parse");
    assert!(facade.contains(
        "pyo3_stub_gen::reexport_module_members!(\"fmp.statements.growth.income\" from \"fmp._native.statements.growth.income\");\n"
    ));
    assert!(!facade.contains("errors"));
}
