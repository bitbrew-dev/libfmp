//! Committed-source generator for the `fmp-py` response models.
//!
//! Parses every response struct under `crates/libfmp/src/responses`, classifies
//! each field by its libfmp newtype, and emits a typed `pyo3` `pyclass` model
//! that unwraps the newtype into a Python-native value. Run it with
//! `cargo run -p fmp-py-gen --bin gen_models`. The generator lives in its own
//! crate so it builds even when `fmp-py` does not compile.

mod classify;
mod emit;
mod model;
mod parse;

use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;

use syn::{Fields, Item};

use crate::classify::is_passthrough_name;
use crate::emit::{emit_module_tree, emit_struct, model_file_path, run_rustfmt};
use crate::model::{FieldDef, Registry, Report, StructDef};
use crate::parse::{
    base_ident, collect_rust_files, is_public, module_path_for, technical_indicator_structs,
};

pub(crate) const GENERATED_HEADER: &str = "// @generated by gen_models; do not edit by hand.";
pub(crate) const RUST_EDITION: &str = "2024";

pub(crate) type BoxError = Box<dyn std::error::Error>;

fn main() -> Result<(), BoxError> {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let responses_root = manifest.join("../libfmp/src/responses").canonicalize()?;
    let models_root = manifest.join("../fmp-py/src/models");

    let mut files = Vec::new();
    collect_rust_files(&responses_root, &mut files)?;
    files.sort();

    let mut structs = Vec::new();
    let mut registry = Registry {
        structs: BTreeMap::new(),
        aliases: BTreeMap::new(),
        module_public: BTreeMap::new(),
    };

    for file in &files {
        let module_path = module_path_for(file, &responses_root);
        let content = fs::read_to_string(file)?;
        let parsed = syn::parse_file(&content)?;
        let stem = module_path.last().cloned().unwrap_or_default();
        if stem == "technical_indicators" {
            for def in technical_indicator_structs(&parsed, &module_path)? {
                register(&mut registry, &def);
                structs.push(def);
            }
        }
        for item in &parsed.items {
            match item {
                Item::Mod(item) => {
                    registry.module_public.insert(
                        (module_path.clone(), item.ident.to_string()),
                        is_public(&item.vis),
                    );
                }
                Item::Struct(item) if is_public(&item.vis) => {
                    if let Fields::Named(named) = &item.fields {
                        let fields = named
                            .named
                            .iter()
                            .filter_map(|field| {
                                field.ident.as_ref().map(|ident| FieldDef {
                                    name: ident.to_string(),
                                    ty: field.ty.clone(),
                                })
                            })
                            .collect();
                        let def = StructDef {
                            name: item.ident.to_string(),
                            module_path: module_path.clone(),
                            fields,
                        };
                        register(&mut registry, &def);
                        structs.push(def);
                    }
                }
                Item::Type(item) if is_public(&item.vis) => {
                    let name = item.ident.to_string();
                    if !is_passthrough_name(&name)
                        && let Some(target) = base_ident(&item.ty)
                    {
                        registry.aliases.insert(name, target);
                    }
                }
                _ => {}
            }
        }
    }

    let src_root = responses_root
        .parent()
        .ok_or("responses directory has no parent")?
        .to_path_buf();
    for definition in ["types.rs", "codecs.rs", "query.rs"] {
        let content = fs::read_to_string(src_root.join(definition))?;
        let parsed = syn::parse_file(&content)?;
        for item in &parsed.items {
            if let Item::Type(item) = item
                && is_public(&item.vis)
            {
                let name = item.ident.to_string();
                if !is_passthrough_name(&name)
                    && let Some(target) = base_ident(&item.ty)
                {
                    registry.aliases.entry(name).or_insert(target);
                }
            }
        }
    }

    let mut by_module: BTreeMap<Vec<String>, Vec<&StructDef>> = BTreeMap::new();
    for def in &structs {
        by_module
            .entry(def.module_path.clone())
            .or_default()
            .push(def);
    }

    let mut report = Report::default();
    let mut written = Vec::new();

    for (module_path, defs) in &by_module {
        let mut body = String::new();
        for def in defs {
            emit_struct(def, &registry, &mut body, &mut report);
        }
        let file_path = model_file_path(&models_root, module_path);
        let mut file_content = String::new();
        file_content.push_str(GENERATED_HEADER);
        file_content.push_str("\n\n");
        file_content.push_str("use pyo3::IntoPyObjectExt;\n");
        file_content.push_str("use pyo3::prelude::*;\n");
        file_content.push_str("use pyo3::types::PyTuple;\n");
        file_content
            .push_str("use pyo3_stub_gen::derive::{gen_stub_pyclass, gen_stub_pymethods};\n\n");
        file_content.push_str(&body);
        if let Some(parent) = file_path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&file_path, file_content)?;
        written.push(file_path);
        report.emitted += defs.len();
    }

    for mod_file in emit_module_tree(&models_root, &by_module)? {
        written.push(mod_file);
    }

    run_rustfmt(&written)?;

    report.print(&structs.len());
    Ok(())
}

/// Records a struct in the name-to-module registry.
fn register(registry: &mut Registry, def: &StructDef) {
    registry
        .structs
        .insert(def.name.clone(), def.module_path.clone());
}
