#!/usr/bin/env python3
"""Generate runtime re-export modules for fmp's native classes.

The extension exposes private backing symbols, while ordinary Python modules
provide canonical import metadata and the stable public names. Public classes
declared in each ``.pyi`` are re-exported automatically.

This script keeps those shims in sync with the ``.pyi`` set: it writes a shim for
every ``python/fmp/<name>.pyi`` (except ``__init__``), and removes any orphaned
shim it previously generated whose ``.pyi`` is gone. Run with ``--check`` to only
report drift (used in CI); the default rewrites and exits non-zero on any change,
matching the autofix hook convention.
"""

from __future__ import annotations

# standard library
import ast
import sys
from pathlib import Path

MARKER = "generated by scripts/gen_submodule_shims.py"

PKG_DIR = Path(__file__).resolve().parent.parent / "python" / "fmp"


def public_classes(pyi: Path) -> list[str]:
    tree = ast.parse(pyi.read_text(encoding="utf-8"), filename=str(pyi))
    return [
        node.name
        for node in tree.body
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_")
    ]


def shim_body(name: str, classes: list[str]) -> str:
    imports = "\n".join(
        f"from fmp._native import _{class_name} as {class_name}"
        for class_name in sorted(classes)
    )
    exported = "\n".join(f'    "{class_name}",' for class_name in classes)
    return (
        f'"""Public ``fmp.{name}`` types backed by the native extension.\n\n'
        f"Auto-{MARKER} from ``{name}.pyi``; do not edit by hand.\n"
        f'"""\n\n# fmp library\n{imports}\n\n'
        f"__all__ = [\n{exported}\n]\n"
    )


def native_marker_body() -> str:
    return (
        '"""Source marker for the compiled ``fmp._native`` extension.\n\n'
        "The extension module takes precedence at runtime. This file lets static type\n"
        "checkers pair the compiled module with ``_native.pyi``.\n\n"
        f"Auto-{MARKER} from ``_native.pyi``; do not edit by hand.\n"
        '"""\n'
    )


def module_classes(pkg_dir: Path) -> dict[str, list[str]]:
    return {
        pyi.stem: public_classes(pyi)
        for pyi in sorted(pkg_dir.glob("*.pyi"))
        if pyi.stem not in {"__init__", "_native"}
    }


def native_stub_body(classes_by_module: dict[str, list[str]]) -> str:
    imports: list[str] = []
    declarations: list[str] = []
    for module, classes in classes_by_module.items():
        for class_name in sorted(classes):
            imports.append(
                f"from fmp.{module} import {class_name} as _{class_name}Type"
            )
            declarations.append(f"_{class_name}: type[_{class_name}Type]")
    joined_imports = "\n".join(imports)
    joined_declarations = "\n".join(declarations)
    return (
        f"# Auto-{MARKER} from the public module stubs; do not edit by hand.\n"
        f"\n# fmp library\n{joined_imports}\n\n"
        f"__version__: str\n{joined_declarations}\n"
    )


def desired_shims(classes_by_module: dict[str, list[str]]) -> dict[str, str]:
    shims = {"_native": native_marker_body()}
    for name, classes in classes_by_module.items():
        shims[name] = shim_body(name, classes)
    return shims


def is_generated_shim(path: Path) -> bool:
    if not path.is_file():
        return False
    if path.name == "__init__.py":
        return False
    return MARKER in path.read_text(encoding="utf-8")


def run(pkg_dir: Path, check: bool) -> int:
    classes_by_module = module_classes(pkg_dir)
    wanted = desired_shims(classes_by_module)
    changes: list[str] = []

    native_stub = pkg_dir / "_native.pyi"
    wanted_native_stub = native_stub_body(classes_by_module)
    if native_stub.read_text(encoding="utf-8") != wanted_native_stub:
        changes.append("stale: _native.pyi")
        if not check:
            native_stub.write_text(wanted_native_stub, encoding="utf-8")

    for name, body in wanted.items():
        target = pkg_dir / f"{name}.py"
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != body:
            changes.append(
                f"{'stale' if current is not None else 'missing'}: {name}.py"
            )
            if not check:
                target.write_text(body, encoding="utf-8")

    for py in sorted(pkg_dir.glob("*.py")):
        name = py.stem
        if name in wanted or name == "__init__":
            continue
        if is_generated_shim(py):
            changes.append(f"orphaned: {py.name}")
            if not check:
                py.unlink()

    if changes:
        verb = "would update" if check else "updated"
        print(f"submodule shims {verb}:", file=sys.stderr)
        for c in changes:
            print(f"  {c}", file=sys.stderr)
        return 1
    return 0


def main() -> int:
    check = "--check" in sys.argv[1:]
    return run(PKG_DIR, check=check)


if __name__ == "__main__":
    raise SystemExit(main())
