// Package fmp is a pure Go client for the Financial Modeling Prep (FMP) HTTP
// API. It mirrors the Rust crate libfmp one-for-one: the same client options,
// the same authentication modes, the same error categories, and the same
// transport rules.
//
// The module path ends in "go", so import it with an alias:
//
//	import fmp "github.com/bitbrew-dev/libfmp/sdk/go"
//
// # Building a client
//
// NewClient validates every option before any request is made and returns a
// *Error of category CategoryConfiguration when the configuration is unsafe
// or inconsistent. Direct access to the default FMP origin requires explicit
// authentication:
//
//	auth, ok := fmp.FMPHeaderFromEnv()
//	if !ok {
//		return errors.New("FMP_API_KEY is not set")
//	}
//	client, err := fmp.NewClient(fmp.WithAuthentication(auth))
//
// Header authentication modes (FMPHeader, Bearer, CustomHeader,
// CustomHeaderWithPrefix) never place a credential in the URL. Query modes
// (FMPQuery, CustomQuery) append the secret as the last query pair of every
// request. CustomHeaderWithPrefix sends the header value as prefix followed
// by secret with no separator inserted, mirroring the Rust
// Authentication::custom_header(name, Some(prefix), secret) form; an empty
// prefix is the same value as CustomHeader. The Example functions of this
// package and the programs under examples/ show these calls end to end,
// offline, against an in-process server.
//
// # Transport rules
//
// The client is standard-library only and builds with CGO_ENABLED=0. It never
// retries: every call issues exactly one request per redirect hop, whatever
// the status. Redirects are followed only to the same origin and at most ten
// times; RedirectNone returns the redirect as a status error instead. One
// context deadline (WithTimeout, default 30 seconds) spans the whole call,
// including redirects and the body read. Response bodies are capped by
// WithMaxResponseBodyBytes (default 64 MiB). Until those options are set,
// CSV bulk calls use DefaultBulkTimeout (600 seconds) and
// DefaultBulkMaxResponseBodyBytes (256 MiB) instead.
//
// WithHTTPClient injects a caller-owned *http.Client for proxies and tests.
// The SDK shallow-copies it to install its redirect policy, so the caller's
// value is never mutated. WithConnectTimeout applies only to the transport
// the SDK builds itself; a caller-supplied client keeps its own dialer.
//
// # Credential policy
//
// No credential can reach a diagnostic. Authentication, Client, and Redactor
// implement fmt.Formatter so that %v, %+v, and %#v print a description
// without secret values. Every transport failure is rebuilt without the
// request URL before it escapes (Go's *url.Error embeds the URL, which holds
// the API key in query mode), and its cause text is passed through the
// Redactor. The cause text also loses the network topology a dial or proxy
// failure prints (the base URL host, the resolved proxy host, and the
// addresses a *net.OpError or *net.DNSError names); provider bodies keep
// such text. Provider bodies retained in an *Error are redacted and capped at
// MaxSafeBodyBytes.
//
// # Environment
//
// FMPHeaderFromEnv reads FMP_API_KEY. NewClient never reads a credential
// from the environment; it consults the proxy variables (HTTP_PROXY,
// HTTPS_PROXY, NO_PROXY) once through the transport's proxy function, as the
// first request would, to register the proxy host for cause redaction. The
// opt-in live tests (live_test.go) use the same names as the Rust crate's
// live_opt_in.rs: FMP_LIVE_TESTS=1 switches both tests on,
// the direct test needs FMP_API_KEY, and the proxy test needs
// FMP_PROXY_BASE_URL, FMP_PROXY_TOKEN, and optionally FMP_PROXY_PATH_PREFIX
// (default router/stable) and FMP_TENANT. They skip without the switch; run
// them from sdk/go with:
//
//	FMP_LIVE_TESTS=1 FMP_API_KEY=... go test -run 'TestLive' -count=1 ./...
//
// # Endpoint surface
//
// Endpoint methods are generated from the registry that also drives the
// Python binding (cargo run -p fmp-py-gen --bin gen_go), so the public names
// follow fixed rules rather than per-endpoint choices. Every generated
// file starts with "Code generated by fmp-py-gen gen_go. DO NOT EDIT.": one
// <domain>_models.go and one <domain>.go per domain, queries.go for the query
// types more than one domain shares, namespaces.go for the Namespaces struct
// Client embeds, and metadata_table.go for the advisory endpoint metadata.
// These are the decisions settled by the hand-written quote domain (ADR
// 0030, phase 0):
//
//   - Namespaces: each registry domain is a struct named <Domain>Namespace,
//     reached as a field of Client through the embedded Namespaces
//     (client.Quote). A domain with nested namespaces nests the structs the
//     same way (client.Statements.Income).
//   - Casing: registry names in UpperCamelCase, with one initialism table
//     (ADR 0032) applied to every generated and hand-written identifier:
//     ID, UID, URL, JSON, API, HTTP, FMP, SEC, US, COT, ETF, CIK, CUSIP, ISIN,
//     IPO, SP500, ESG, DCF, EPS, TTM, and the form names 8K and 13F are all
//     caps, and TipRanks keeps its brand casing. So etfs is ETFs,
//     latest_8k is Latest8K, and the Rust KeyMetricsTtm is KeyMetricsTTM.
//     Struct tags keep the wire names.
//   - Queries: every endpoint with arguments takes a value type named after
//     the Rust query (QuoteQuery) built by New<Query>(required args...), with
//     one With<Setter>(value) builder method per Rust with_* setter. String
//     kinds such as tickers are plain strings, validated when the request is
//     built; a rejected argument returns a *Error of CategoryValidation whose
//     message is "<argument>: <reason>". Endpoints without a query take only
//     the context.
//   - Signatures: func (n *QuoteNamespace) Full(ctx context.Context,
//     q QuoteQuery) ([]Quote, error). The context comes first and bare-array
//     endpoints return a slice of the model.
//   - Models: one <domain>_models.go per domain with camelCase struct tags,
//     pointer fields for optional members, and an UnmarshalJSONFrom that
//     decodes through a pointer-field shadow struct and returns a *Error of
//     CategoryDecode naming the first required member that is missing or
//     null, matching serde. Unknown members are ignored. Members whose Rust
//     codec treats "" as absent (empty_date, empty_or_null_date) decode to a
//     nil *Date; re-encoding writes null, not "", since the SDK is read-only.
//     A member serde skips when None (skip_serializing_if = "Option::is_none")
//     carries the omitzero tag option, so a nil member is omitted on
//     re-encoding exactly as the Rust model omits it. A model whose Rust
//     decoder keeps every unclaimed member in one map (FinancialReportJSON)
//     holds them in a jsontext.Value tagged json:",embed": always a JSON
//     object, {} when nothing is left over, re-emitted in place.
//   - Nested namespaces: a domain with [[namespace]] sub-groups nests one
//     struct per group as an exported field of the domain struct, so the
//     statements domain is reached as client.Statements.Income.Statement.
//   - Accepted response-side differences: a CalendarQuarter member decodes
//     as a plain uint8 with no 1 to 4 range check (Rust validates; the Go
//     parity tests prove the JSON kind only), and a FiscalPeriod member
//     decodes as a plain string rather than the closed FiscalPeriod type the
//     queries use, in the same way IsoTimestamp members stay exact strings.
//   - Dynamic rows: an endpoint whose Rust method returns
//     Vec<DynamicObject> (registry response = "dynamic") returns
//     []jsontext.Value, one raw JSON object per row, checked to be an
//     object and otherwise kept verbatim. SECFilings.SearchIndustryClassifications
//     is the only one today; it stays dynamic in Go for as long as the Rust
//     contract does, since a typed row is a Rust model change first.
//   - Type aliases: a Rust alias of a model (FundDisclosureDate for
//     Form13fFilingDate) has no Go type of its own; the method returns the
//     aliased model's Go type (Form13FFilingDate), so one Rust model is one
//     Go type.
//
// # Endpoint metadata
//
// EndpointMetadataFor returns the advisory metadata the Rust descriptor of an
// endpoint attaches (geography, plan access, a conditional plan, realtime
// caveats, request bounds), keyed by the Go call path without the client:
//
//	metadata, ok := fmp.EndpointMetadataFor("Quote.Full")
//	if ok && metadata.Realtime != nil && metadata.Realtime.Delay != nil {
//		log.Printf("quotes are delayed %s", metadata.Realtime.Delay)
//	}
//
// The types in metadata.go mirror the Rust EndpointMetadata one-for-one and
// every zero value means unspecified; the generated metadata_table.go holds
// one entry per method whose descriptor attaches metadata, and the lookup
// reports false with the zero value for the others and for an unknown key.
// The client never validates a request against the metadata, exactly as the
// Rust crate does not. The surface is one table rather than a sibling
// <Method>Metadata per endpoint method because several methods share one
// endpoint id through helper reuse while carrying different metadata (the id
// "quote" serves five namespaces), so the id cannot be the key, and a table
// keyed by call path adds one generated file instead of 271 methods.
//
// EndpointMetadataByID resolves the endpoint id an *Error carries in its
// Endpoint field. It returns one EndpointMethodMetadata per method that
// sends the id and attaches metadata, never a merged value: seven ids (the
// quote, quote-short, and five chart helpers the asset domains share) carry
// different metadata per method, and the caller picks the entry whose Method
// it called.
