// Package fmp is a pure Go client for the Financial Modeling Prep (FMP) HTTP
// API. It mirrors the Rust crate libfmp one-for-one: the same client options,
// the same authentication modes, the same error categories, and the same
// transport rules.
//
// The module path ends in "go", so import it with an alias:
//
//	import fmp "github.com/bitbrew-dev/libfmp/sdk/go"
//
// # Building a client
//
// NewClient validates every option before any request is made and returns a
// *Error of category CategoryConfiguration when the configuration is unsafe
// or inconsistent. Direct access to the default FMP origin requires explicit
// authentication:
//
//	auth, ok := fmp.FmpHeaderFromEnv()
//	if !ok {
//		return errors.New("FMP_API_KEY is not set")
//	}
//	client, err := fmp.NewClient(fmp.WithAuthentication(auth))
//
// Header authentication modes (FmpHeader, Bearer, CustomHeader) never place a
// credential in the URL. Query modes (FmpQuery, CustomQuery) append the secret
// as the last query pair of every request.
//
// # Transport rules
//
// The client is standard-library only and builds with CGO_ENABLED=0. It never
// retries: every call issues exactly one request per redirect hop, whatever
// the status. Redirects are followed only to the same origin and at most ten
// times; RedirectNone returns the redirect as a status error instead. One
// context deadline (WithTimeout, default 30 seconds) spans the whole call,
// including redirects and the body read. Response bodies are capped by
// WithMaxResponseBodyBytes (default 64 MiB).
//
// WithHTTPClient injects a caller-owned *http.Client for proxies and tests.
// The SDK shallow-copies it to install its redirect policy, so the caller's
// value is never mutated. WithConnectTimeout applies only to the transport
// the SDK builds itself; a caller-supplied client keeps its own dialer.
//
// # Credential policy
//
// No credential can reach a diagnostic. Authentication, Client, and Redactor
// implement fmt.Formatter so that %v, %+v, and %#v print a description
// without secret values. Every transport failure is rebuilt without the
// request URL before it escapes (Go's *url.Error embeds the URL, which holds
// the API key in query mode), and its cause text is passed through the
// Redactor. Provider bodies retained in an *Error are redacted and capped at
// MaxSafeBodyBytes.
//
// # Environment
//
// FmpHeaderFromEnv reads FMP_API_KEY. The live opt-in tests of the Rust crate
// use FMP_LIVE_TESTS=1, FMP_API_KEY, FMP_PROXY_BASE_URL, FMP_PROXY_TOKEN,
// FMP_PROXY_PATH_PREFIX, and FMP_TENANT; the Go module uses the same names
// once its live tests exist. NewClient itself never reads the environment.
//
// # Endpoint surface
//
// Endpoint methods are generated from the registry that also drives the
// Python binding (cargo run -p fmp-py-gen --bin gen_go), so the public names
// follow mechanical rules rather than a hand-curated table. Every generated
// file starts with "Code generated by fmp-py-gen gen_go. DO NOT EDIT.": one
// <domain>_models.go and one <domain>.go per domain, queries.go for the query
// types more than one domain shares, and namespaces.go for the Namespaces
// struct Client embeds. These are the decisions settled by the hand-written
// quote domain (ADR 0030, phase 0):
//
//   - Namespaces: each registry domain is a struct named <Domain>Namespace,
//     reached as a field of Client through the embedded Namespaces
//     (client.Quote). A domain with nested namespaces nests the structs the
//     same way (client.Statements.Income).
//   - Method casing: the registry entry name in UpperCamelCase with mechanical
//     casing and no initialism table: etfs is Etfs, batch_quote_short is
//     BatchQuoteShort. Predictable generation wins over Go initialism style.
//   - Queries: every endpoint with arguments takes a value type named after
//     the Rust query (QuoteQuery) built by New<Query>(required args...), with
//     one With<Setter>(value) builder method per Rust with_* setter. String
//     kinds such as tickers are plain strings, validated when the request is
//     built; a rejected argument returns a *Error of CategoryValidation whose
//     message is "<argument>: <reason>". Endpoints without a query take only
//     the context.
//   - Signatures: func (n *QuoteNamespace) Full(ctx context.Context,
//     q QuoteQuery) ([]Quote, error). The context comes first and bare-array
//     endpoints return a slice of the model.
//   - Models: one <domain>_models.go per domain with camelCase struct tags,
//     pointer fields for optional members, and an UnmarshalJSONFrom that
//     decodes through a pointer-field shadow struct and returns a *Error of
//     CategoryDecode naming the first required member that is missing or
//     null, matching serde. Unknown members are ignored. Members whose Rust
//     codec treats "" as absent (empty_date, empty_or_null_date) decode to a
//     nil *Date; re-encoding writes null, not "", since the SDK is read-only.
//     A member serde skips when None (skip_serializing_if = "Option::is_none")
//     carries the omitzero tag option, so a nil member is omitted on
//     re-encoding exactly as the Rust model omits it.
